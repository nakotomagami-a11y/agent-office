#!/usr/bin/env node
// Regenerates src/route-table.ts from the src/routes/**/route.ts tree.
// Run `pnpm --filter @agent-office/server routes` after adding, moving or deleting a route;
// router.test.ts fails while the table and the tree disagree.
import { globSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SRC = join(dirname(fileURLToPath(import.meta.url)), "..", "src");

const files = globSync("routes/**/route.ts", { cwd: SRC })
  .map((f) => f.split("\\").join("/"))
  .sort();

const entries = files.map((file, i) => {
  const dir = file.slice("routes".length, -"/route.ts".length);
  // Next folder conventions router.ts does not implement: catch-all, route groups, private folders, slots.
  if (/\[\[?\.\.\.|\/[(_@]/.test(dir)) throw new Error(`folder convention not supported by router.ts: ${file}`);
  return { name: `r${i}`, path: `/api${dir}`, spec: `./${file.slice(0, -".ts".length)}` };
});

const out = [
  "// GENERATED by scripts/gen-route-table.mjs — do not edit; run `pnpm --filter @agent-office/server routes`.",
  'import type { RouteEntry } from "./router";',
  ...entries.map((e) => `import * as ${e.name} from "${e.spec}";`),
  "",
  "export const ROUTES: readonly RouteEntry[] = [",
  ...entries.map((e) => `  { path: "${e.path}", module: ${e.name} },`),
  "];",
  "",
].join("\n");

writeFileSync(join(SRC, "route-table.ts"), out);
console.log(`route-table.ts: ${entries.length} routes`);
